// Map a subject name to a sensible Lucide icon (falls back to a book).
const SUBJECT_ICON = {
  english: 'notebook-pen',
  mathematics: 'calculator',
  math: 'calculator',
  maths: 'calculator',
  biology: 'dna',
  chemistry: 'flask-conical',
  physics: 'atom',
  history: 'landmark',
  geography: 'globe',
  economics: 'trending-up',
};

export function subjectIcon(name) {
  return SUBJECT_ICON[(name || '').trim().toLowerCase()] || 'book';
}

// Return a complete inline <svg> string for `name`, sized and theme-aware.
export function icon(name, { size = 20, cls = '' } = {}) {
  const inner = ICONS[name] || ICONS.book;
  return (
    `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" ` +
    'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" ' +
    `stroke-linejoin="round" aria-hidden="true">${inner}</svg>`
  );
}

// Fill every element that has a data-icon="<name>" attribute with its SVG.

export function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]:not(option)').forEach((el) => {
    const size = Number(el.dataset.iconSize) || 24;
    el.innerHTML = icon(el.dataset.icon, { size });
  });
}
